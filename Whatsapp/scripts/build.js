const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const dist = path.join(root, "dist");

function rmIfExists(targetPath) {
  if (fs.existsSync(targetPath)) {
    fs.rmSync(targetPath, { recursive: true, force: true });
  }
}

function copyIfExists(srcRelative, destRelative = srcRelative) {
  const src = path.join(root, srcRelative);
  const dest = path.join(dist, destRelative);

  if (!fs.existsSync(src)) {
    return;
  }

  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.cpSync(src, dest, { recursive: true });
}

function build() {
  rmIfExists(dist);
  fs.mkdirSync(dist, { recursive: true });

  copyIfExists("server.js");
  copyIfExists("send-whatsapp.js");
  copyIfExists("public");
  copyIfExists("src");

  const packageJsonPath = path.join(root, "package.json");
  const packageJson = JSON.parse(fs.readFileSync(packageJsonPath, "utf8"));

  const distPackageJson = {
    name: packageJson.name,
    version: packageJson.version,
    private: true,
    description: packageJson.description,
    main: "server.js",
    scripts: {
      start: "node server.js"
    },
    dependencies: packageJson.dependencies || {}
  };

  fs.writeFileSync(path.join(dist, "package.json"), JSON.stringify(distPackageJson, null, 2));

  const lockPath = path.join(root, "package-lock.json");
  if (fs.existsSync(lockPath)) {
    copyIfExists("package-lock.json");
  }

  const readme = `# Production Build\n\nThis folder is generated by npm run build.\n\n## Run on server\n\n1. npm install --omit=dev\n2. npm start\n`;
  fs.writeFileSync(path.join(dist, "README.md"), readme);

  console.log("Build completed: dist folder is ready for server deploy.");
}

build();
